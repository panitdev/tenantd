//! Processes inside running sandboxes. Only processes tenantd started are
//! visible or addressable.
//!
//! A start follows the intent pattern: the row is inserted as `starting`
//! under the sandbox lock (so a stop can't race it and `max_processes` holds),
//! exec runs under the process lock, and the row turns `running` once the
//! PID is known. A crash in between leaves a `starting` row that reconcile
//! adopts (the runtime recorded a PID that is still alive) or marks `lost`.

use std::sync::Arc;
use std::time::Duration;

use futures::stream::{self, BoxStream, StreamExt};
use tokio::sync::watch;
use tokio::time::Instant;
use tracing::{info, warn};

use crate::Tenantd;
use crate::backend::RuntimeHandle;
use crate::events::EventKind;
use crate::model::{
    ProcessRecord, ProcessSpec, ProcessState, ProcessTombstone, ResolvedProcess, SandboxState,
    Signal, Stream,
};
use crate::{Bytes, Error, ProcessKey, Result, SandboxKey, now, policy};

/// Largest `Data` chunk a read sends.
pub const OUTPUT_CHUNK: usize = 64 << 10;
/// How often a follower re-checks a growing file between state changes.
const FOLLOW_POLL: Duration = Duration::from_millis(100);

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum OutputChunk {
    Data {
        offset: Bytes,
        bytes: Vec<u8>,
    },
    /// The read reached the stream's limit and `dropped` bytes past it were
    /// discarded. Generated by the read path; never stored.
    Truncated {
        offset: Bytes,
        dropped: Bytes,
    },
}

impl Tenantd {
    /// Idempotent on the key: the same spec returns the existing process, a
    /// different one (or an ID still reserved by a tombstone) is
    /// `AlreadyExists`. The sandbox must be running.
    pub async fn start_process(&self, key: ProcessKey, spec: ProcessSpec) -> Result<ProcessRecord> {
        policy::validate_process_spec(&spec)?;
        self.require_enforcement()?;
        self.require_unblocked(&key.tenant)?;
        if let Some(r) = self.existing_process(&key, &spec).await? {
            return Ok(r);
        }

        let sk = key.sandbox_key();
        let sandbox_lock = self.sandbox_locks.lock(sk.clone()).await;
        let sandbox = self.get_sandbox(&key.tenant, &key.sandbox).await?;
        if sandbox.state != SandboxState::Running {
            return Err(Error::FailedPrecondition(format!(
                "sandbox {sk} is {}",
                sandbox.state.as_str()
            )));
        }
        if let Some(r) = self.existing_process(&key, &spec).await? {
            return Ok(r);
        }
        let cfg = self.config();
        let (resolved, limits) = policy::plan_process(&cfg, &sandbox, key.clone(), &spec)?;
        let max = cfg.profile(&sandbox.profile)?.exec.max_processes as usize;
        let live = self
            .state
            .list_processes(Some(&sk))
            .await?
            .iter()
            .filter(|p| p.state.is_live())
            .count();
        if live >= max {
            return Err(Error::denied(
                format!("profiles.{}.exec.max_processes", sandbox.profile),
                format!("sandbox {sk} already has {live} live processes"),
            ));
        }
        let ts = now();
        let mut rec = ProcessRecord {
            tenant: key.tenant.clone(),
            sandbox: key.sandbox.clone(),
            id: key.id.clone(),
            io: self
                .output
                .io(&self.storage.tenant_dir(&key.tenant), &key.sandbox, &key.id),
            spec,
            limits,
            state: ProcessState::Starting,
            pid: None,
            exit_code: None,
            signal: None,
            stdout_dropped: 0,
            stderr_dropped: 0,
            created_at: ts,
            updated_at: ts,
            exited_at: None,
        };
        self.state.insert_process(&rec).await?;
        let _p = self.process_locks.lock(key.clone()).await;
        drop(sandbox_lock);
        self.bump_processes();

        match self.exec_process(&mut rec, &resolved).await {
            Ok(()) => Ok(rec),
            Err(e) => {
                warn!(process = %key, error = %e, "process start failed, rolling back");
                self.undo_start(&rec).await?;
                Err(e)
            }
        }
    }

    /// A row (or a live tombstone) for `key`, checked against `spec`. A row
    /// still `starting` is re-read once its in-flight start finishes.
    async fn existing_process(
        &self,
        key: &ProcessKey,
        spec: &ProcessSpec,
    ) -> Result<Option<ProcessRecord>> {
        let mut row = self.state.get_process(key).await?;
        if row
            .as_ref()
            .is_some_and(|r| r.state == ProcessState::Starting)
        {
            let _p = self.process_locks.lock(key.clone()).await;
            row = self.state.get_process(key).await?;
        }
        if let Some(r) = row {
            return if r.spec == *spec {
                Ok(Some(self.with_live_counts(r).await))
            } else {
                Err(Error::AlreadyExists(format!(
                    "process {key} exists with a different spec"
                )))
            };
        }
        match self.state.get_tombstone(key).await? {
            Some(t) if t.expires_at > now() => {
                let what = if t.spec_digest == spec.digest() {
                    "already ran and was removed"
                } else {
                    "was used by an earlier process"
                };
                Err(Error::AlreadyExists(format!(
                    "process {key} {what}; the ID is reserved until {}",
                    t.expires_at
                )))
            }
            _ => Ok(None),
        }
    }

    /// Steps 2-3 of a start. Caller holds the process lock.
    async fn exec_process(&self, rec: &mut ProcessRecord, p: &ResolvedProcess) -> Result<()> {
        let h = RuntimeHandle::for_key(&rec.sandbox_key());
        self.output.prepare(&rec.io).await?;
        // Armed before the first byte is written, so the limit holds from
        // the start.
        self.output.watch(&rec.io, rec.limits.output_limit).await?;
        let pid = self.runtime.exec(&h, p, &rec.io).await?;
        rec.pid = Some(pid);
        self.set_process_state(rec, ProcessState::Running).await?;
        info!(process = %rec.key(), pid, "process running");
        if let Err(e) = self.runtime.watch_process(&h, pid).await {
            warn!(process = %rec.key(), error = %e, "watching process failed; reconcile will retry");
        }
        Ok(())
    }

    /// Undo a failed start: kill the process if it got as far as running,
    /// remove its files and its row. The ID is free again. If this fails too
    /// the row stays `starting` for reconcile.
    async fn undo_start(&self, rec: &ProcessRecord) -> Result<()> {
        let h = RuntimeHandle::for_key(&rec.sandbox_key());
        let pid = match rec.pid {
            Some(p) => Some(p),
            None => self.runtime.recorded_pid(&rec.io).await?,
        };
        if let Some(pid) = pid {
            self.runtime.signal(&h, pid, Signal::Kill).await?;
        }
        self.output.remove(&rec.io).await?;
        self.state.delete_process(&rec.key(), None).await?;
        self.bump_processes();
        Ok(())
    }

    pub async fn get_process(&self, key: &ProcessKey) -> Result<ProcessRecord> {
        let rec = self
            .state
            .get_process(key)
            .await?
            .ok_or_else(|| Error::NotFound(format!("process {key}")))?;
        Ok(self.with_live_counts(rec).await)
    }

    pub async fn list_processes(&self, sk: &SandboxKey) -> Result<Vec<ProcessRecord>> {
        self.get_sandbox(&sk.tenant, &sk.sandbox).await?;
        let mut out = Vec::new();
        for r in self.state.list_processes(Some(sk)).await? {
            out.push(self.with_live_counts(r).await);
        }
        Ok(out)
    }

    pub async fn list_all_processes(&self) -> Result<Vec<ProcessRecord>> {
        self.state.list_processes(None).await
    }

    /// Only a running process can be signalled. Returns its current state;
    /// the exit, if the signal causes one, arrives as an event.
    pub async fn signal_process(&self, key: &ProcessKey, sig: Signal) -> Result<ProcessRecord> {
        let _p = self.process_locks.lock(key.clone()).await;
        let rec = self.get_process(key).await?;
        let pid = match (rec.state, rec.pid) {
            (ProcessState::Running, Some(pid)) => pid,
            (state, _) => {
                return Err(Error::FailedPrecondition(format!(
                    "process {key} is {}",
                    state.as_str()
                )));
            }
        };
        self.runtime
            .signal(&RuntimeHandle::for_key(&rec.sandbox_key()), pid, sig)
            .await?;
        info!(process = %key, signal = sig.name(), "process signalled");
        Ok(rec)
    }

    /// Block until the process is no longer live or `timeout` passes
    /// (`None`: no timeout), then return its current state.
    pub async fn wait_process(
        &self,
        key: &ProcessKey,
        timeout: Option<Duration>,
    ) -> Result<ProcessRecord> {
        let deadline = timeout.map(|t| Instant::now() + t);
        let mut rx = self.process_epoch.subscribe();
        loop {
            let rec = self.get_process(key).await?;
            if !rec.state.is_live() {
                return Ok(rec);
            }
            if !wait_change(&mut rx, deadline).await {
                return Ok(rec);
            }
        }
    }

    /// Retained output of one stream from `offset`. Bytes below the
    /// process's output limit come as `Data`; a read that reaches the limit
    /// of a stream that dropped output gets one `Truncated`, then nothing
    /// more from it. With `follow` the stream stays open until the process
    /// is no longer live.
    pub async fn read_output(
        self: &Arc<Self>,
        key: ProcessKey,
        stream: Stream,
        offset: Bytes,
        follow: bool,
    ) -> Result<BoxStream<'static, Result<OutputChunk>>> {
        self.get_process(&key).await?;
        let reader = OutputReader {
            rx: self.process_epoch.subscribe(),
            t: self.clone(),
            key,
            stream,
            offset,
            follow,
            truncated: false,
            done: false,
        };
        Ok(stream::unfold(reader, |mut r| async move {
            if r.done {
                return None;
            }
            match r.next().await {
                Ok(Some(c)) => Some((Ok(c), r)),
                Ok(None) => None,
                Err(e) => {
                    r.done = true;
                    Some((Err(e), r))
                }
            }
        })
        .boxed())
    }

    /// Remove an exited or lost process's row and output, keeping a
    /// tombstone so its ID isn't reused. A live process needs `force`
    /// (SIGKILL first). Deleting a missing process succeeds.
    pub async fn delete_process(&self, key: &ProcessKey, force: bool) -> Result<()> {
        let _p = self.process_locks.lock(key.clone()).await;
        let Some(mut rec) = self.state.get_process(key).await? else {
            return Ok(());
        };
        if rec.state.is_live() {
            if !force {
                return Err(Error::FailedPrecondition(format!(
                    "process {key} is {}; signal it or pass force",
                    rec.state.as_str()
                )));
            }
            let pid = match rec.pid {
                Some(p) => Some(p),
                None => self.runtime.recorded_pid(&rec.io).await?,
            };
            if let Some(pid) = pid {
                let h = RuntimeHandle::for_key(&rec.sandbox_key());
                self.runtime.signal(&h, pid, Signal::Kill).await?;
            }
            self.finish_process(&mut rec, ProcessState::Exited, None, None)
                .await?;
        }
        self.remove_process(&rec).await?;
        info!(process = %key, "process deleted");
        Ok(())
    }

    /// Drop the output and the row, leaving a tombstone. Caller holds the
    /// process lock.
    pub(crate) async fn remove_process(&self, rec: &ProcessRecord) -> Result<()> {
        self.output.remove(&rec.io).await?;
        let tomb = ProcessTombstone {
            key: rec.key(),
            spec_digest: rec.spec.digest(),
            expires_at: now().saturating_add(rec.limits.tombstone_secs as i64),
        };
        self.state.delete_process(&rec.key(), Some(&tomb)).await?;
        self.bump_processes();
        Ok(())
    }

    /// A runtime exit report for `pid` in sandbox `sk`.
    pub(crate) async fn on_process_exit(
        &self,
        sk: &SandboxKey,
        pid: u32,
        exit_code: Option<i32>,
        signal: Option<i32>,
    ) {
        let Ok(rows) = self.state.list_processes(Some(sk)).await else {
            return;
        };
        for row in rows
            .into_iter()
            .filter(|r| r.pid == Some(pid) && r.state == ProcessState::Running)
        {
            let _p = self.process_locks.lock(row.key()).await;
            let Ok(Some(mut rec)) = self.state.get_process(&row.key()).await else {
                continue;
            };
            if rec.state != ProcessState::Running || rec.pid != Some(pid) {
                continue;
            }
            if let Err(e) = self
                .finish_process(&mut rec, ProcessState::Exited, exit_code, signal)
                .await
            {
                warn!(process = %rec.key(), error = %e, "recording process exit failed; reconcile will retry");
            }
        }
    }

    /// Every live process of a sandbox that is going away ends: running ones
    /// as `exited` (no exit code), starting ones as `lost`. Caller holds the
    /// sandbox lock.
    pub(crate) async fn end_processes(&self, sk: &SandboxKey) -> Result<()> {
        for row in self.state.list_processes(Some(sk)).await? {
            if !row.state.is_live() {
                continue;
            }
            let _p = self.process_locks.lock(row.key()).await;
            let Some(mut rec) = self.state.get_process(&row.key()).await? else {
                continue;
            };
            let state = match rec.state {
                ProcessState::Running => ProcessState::Exited,
                ProcessState::Starting => ProcessState::Lost,
                _ => continue,
            };
            self.finish_process(&mut rec, state, None, None).await?;
        }
        Ok(())
    }

    /// Record the end of a process: final trim, dropped byte counts, state,
    /// and a `ProcessExited` event. Caller holds the process lock.
    pub(crate) async fn finish_process(
        &self,
        rec: &mut ProcessRecord,
        state: ProcessState,
        exit_code: Option<i32>,
        signal: Option<i32>,
    ) -> Result<()> {
        self.output.unwatch(&rec.io).await;
        let limit = rec.limits.output_limit;
        if let Err(e) = self.output.trim(&rec.io, limit).await {
            warn!(process = %rec.key(), error = %e, "final output trim failed");
        }
        match self.output.sizes(&rec.io).await {
            Ok((out, err)) => {
                rec.stdout_dropped = out.saturating_sub(limit);
                rec.stderr_dropped = err.saturating_sub(limit);
            }
            Err(e) => warn!(process = %rec.key(), error = %e, "reading output sizes failed"),
        }
        rec.exit_code = exit_code;
        rec.signal = signal;
        rec.exited_at = Some(now());
        self.set_process_state(rec, state).await?;
        info!(process = %rec.key(), state = state.as_str(), ?exit_code, ?signal, "process ended");
        self.emit(EventKind::ProcessExited {
            key: rec.key(),
            exit_code,
            signal,
            stdout_dropped: rec.stdout_dropped,
            stderr_dropped: rec.stderr_dropped,
        });
        Ok(())
    }

    pub(crate) async fn set_process_state(
        &self,
        rec: &mut ProcessRecord,
        state: ProcessState,
    ) -> Result<()> {
        rec.state = state;
        rec.updated_at = now();
        self.state.update_process(rec).await?;
        self.bump_processes();
        Ok(())
    }

    /// Re-attach to a running process after a restart: output limit and
    /// exit watch. Both are idempotent.
    pub(crate) async fn arm_process(&self, rec: &ProcessRecord) -> Result<()> {
        let pid = rec
            .pid
            .ok_or_else(|| Error::Internal(format!("process {} has no pid", rec.key())))?;
        self.output.watch(&rec.io, rec.limits.output_limit).await?;
        self.runtime
            .watch_process(&RuntimeHandle::for_key(&rec.sandbox_key()), pid)
            .await
    }

    /// Dropped byte counts are final on the row once a process ends; while
    /// it is live they come from the files.
    async fn with_live_counts(&self, mut rec: ProcessRecord) -> ProcessRecord {
        if rec.state.is_live()
            && let Ok((out, err)) = self.output.sizes(&rec.io).await
        {
            rec.stdout_dropped = out.saturating_sub(rec.limits.output_limit);
            rec.stderr_dropped = err.saturating_sub(rec.limits.output_limit);
        }
        rec
    }

    pub(crate) fn bump_processes(&self) {
        self.process_epoch.send_modify(|n| *n = n.wrapping_add(1));
    }
}

/// Wait for a process state change or `deadline`. False once the deadline
/// has passed.
async fn wait_change(rx: &mut watch::Receiver<u64>, deadline: Option<Instant>) -> bool {
    let changed = async {
        if rx.changed().await.is_err() {
            tokio::time::sleep(FOLLOW_POLL).await;
        }
    };
    match deadline {
        Some(d) => tokio::time::timeout_at(d, changed).await.is_ok(),
        None => {
            changed.await;
            true
        }
    }
}

struct OutputReader {
    t: Arc<Tenantd>,
    rx: watch::Receiver<u64>,
    key: ProcessKey,
    stream: Stream,
    offset: Bytes,
    follow: bool,
    truncated: bool,
    done: bool,
}

impl OutputReader {
    async fn next(&mut self) -> Result<Option<OutputChunk>> {
        loop {
            // The row is read before the sizes: if it says the process ended,
            // the sizes read after it include everything it wrote.
            let Some(rec) = self.t.state.get_process(&self.key).await? else {
                return Ok(None);
            };
            let limit = rec.limits.output_limit;
            let (out, err) = self.t.output.sizes(&rec.io).await?;
            let size = match self.stream {
                Stream::Stdout => out,
                Stream::Stderr => err,
            };
            let end = size.min(limit);
            if self.offset < end {
                let n = (end - self.offset).min(OUTPUT_CHUNK as u64) as usize;
                let bytes = self
                    .t
                    .output
                    .read(&rec.io, self.stream, self.offset, n)
                    .await?;
                if !bytes.is_empty() {
                    let offset = self.offset;
                    self.offset += bytes.len() as u64;
                    return Ok(Some(OutputChunk::Data { offset, bytes }));
                }
            } else if size > limit && !self.truncated {
                self.truncated = true;
                return Ok(Some(OutputChunk::Truncated {
                    offset: limit,
                    dropped: size - limit,
                }));
            }
            if !self.follow || !rec.state.is_live() {
                return Ok(None);
            }
            let tick = Instant::now() + FOLLOW_POLL;
            wait_change(&mut self.rx, Some(tick)).await;
        }
    }
}
